import { ReviewClient } from "./review-client.js";

const client = new ReviewClient();
const state = {
  reviews: [],
  selected: null,
  detail: null,
  decisions: new Map(),
};

const els = {
  shell: document.querySelector(".review-shell"),
  serviceState: document.querySelector("#service-state"),
  refreshButton: document.querySelector("#refresh-button"),
  reviewCount: document.querySelector("#review-count"),
  globalAlerts: document.querySelector("#global-alerts"),
  reviewList: document.querySelector("#review-list"),
  detailEmpty: document.querySelector("#detail-empty"),
  detail: document.querySelector("#review-detail"),
  reviewTemplate: document.querySelector("#review-item-template"),
  findingTemplate: document.querySelector("#finding-template"),
};

els.refreshButton.addEventListener("click", () => loadReviews({ preserveSelection: true }));
window.addEventListener("popstate", () => restoreSelectionFromUrl());

loadReviews({ preserveSelection: false });

async function loadReviews({ preserveSelection }) {
  setBusy(true);
  renderAlert("Loading reviews.", "info");
  try {
    const [health, list] = await Promise.all([client.health(), client.listReviews()]);
    els.serviceState.textContent = health.local_only ? "127.0.0.1 only" : "Unsafe host";
    els.serviceState.dataset.state = health.partial || list.partial ? "partial" : "ok";
    state.reviews = list.reviews;
    renderAlerts(list);
    renderReviewList();
    if (preserveSelection && state.selected) {
      await selectReview(state.selected.queueId, state.selected.reviewId, { pushUrl: false });
    } else {
      await restoreSelectionFromUrl();
    }
  } catch (error) {
    els.serviceState.textContent = "Error";
    els.serviceState.dataset.state = "error";
    renderAlert(error.message, "error");
    renderEmpty("Unable to load reviews", "Check that the local Review Panel API is running.");
  } finally {
    setBusy(false);
  }
}

async function restoreSelectionFromUrl() {
  const params = new URLSearchParams(window.location.search);
  const queueId = params.get("queue");
  const reviewId = params.get("review");
  const exists = state.reviews.find((item) => item.queue_id === queueId && item.review_id === reviewId);
  if (exists) {
    await selectReview(queueId, reviewId, { pushUrl: false });
    return;
  }
  if (state.reviews.length > 0) {
    await selectReview(state.reviews[0].queue_id, state.reviews[0].review_id, { pushUrl: true });
    return;
  }
  renderEmpty("No active reviews", "There are no pending review packets in trusted queues.");
}

function renderReviewList() {
  els.reviewList.replaceChildren();
  els.reviewCount.textContent = String(state.reviews.length);
  for (const review of state.reviews) {
    const node = els.reviewTemplate.content.firstElementChild.cloneNode(true);
    node.dataset.queueId = review.queue_id;
    node.dataset.reviewId = review.review_id;
    node.setAttribute("aria-selected", String(isSelected(review.queue_id, review.review_id)));
    node.querySelector(".review-item-title").textContent = review.review_id;
    node.querySelector(".review-item-meta").textContent =
      `${review.queue_kind} · ${review.review_type} · ${review.urgency} · ${review.created_at}`;
    node.querySelector(".review-item-status").textContent =
      `${review.status} · ${review.actionable_findings}/${review.total_findings} actionable`;
    node.addEventListener("click", () => selectReview(review.queue_id, review.review_id, { pushUrl: true }));
    els.reviewList.append(node);
  }
}

async function selectReview(queueId, reviewId, { pushUrl }) {
  state.selected = { queueId, reviewId };
  state.decisions = new Map();
  renderReviewList();
  setBusy(true);
  try {
    state.detail = await client.getReview(queueId, reviewId);
    if (pushUrl) {
      const params = new URLSearchParams({ queue: queueId, review: reviewId });
      history.pushState({}, "", `?${params.toString()}`);
    }
    renderDetail();
  } catch (error) {
    renderEmpty("Unable to open review", error.message);
  } finally {
    setBusy(false);
  }
}

function renderDetail() {
  const detail = state.detail;
  const packet = detail.packet;
  els.detailEmpty.hidden = true;
  els.detail.hidden = false;
  els.detail.replaceChildren();

  const header = document.createElement("header");
  header.className = "detail-header";
  header.innerHTML = `
    <p class="eyebrow">${detail.queue.queue_kind} queue · ${formatStatus(detail.status)}</p>
    <h2>${escapeHtml(packet.review_id)}</h2>
    <p>${escapeHtml(packet.agent_summary)}</p>
    <dl class="detail-grid">
      <div><dt>Type</dt><dd>${escapeHtml(packet.review_type)}</dd></div>
      <div><dt>Urgency</dt><dd>${escapeHtml(packet.urgency)}</dd></div>
      <div><dt>Generated by</dt><dd>${escapeHtml(packet.generated_by)}</dd></div>
      <div><dt>Created</dt><dd>${escapeHtml(packet.created_at)}</dd></div>
    </dl>
  `;
  els.detail.append(header);
  renderSources(detail);
  renderFindings(packet);
  renderSubmitPanel(detail);
}

function renderSources(detail) {
  const section = document.createElement("section");
  section.className = "source-section";
  section.innerHTML = "<h3>Sources</h3>";
  const list = document.createElement("div");
  list.className = "source-list";
  for (const source of detail.source_availability) {
    const row = document.createElement("button");
    row.type = "button";
    row.className = "source-row";
    row.disabled = !source.available;
    row.textContent = `${source.index}. ${source.declared_path} · ${source.available ? "available" : source.reason}`;
    row.addEventListener("click", () => openSource(source.index));
    list.append(row);
  }
  section.append(list);
  const preview = document.createElement("pre");
  preview.id = "source-preview";
  preview.className = "source-preview";
  preview.textContent = "Select an available source to preview it.";
  section.append(preview);
  els.detail.append(section);
}

async function openSource(sourceIndex) {
  const { queueId, reviewId } = state.selected;
  const preview = document.querySelector("#source-preview");
  preview.textContent = "Loading source...";
  try {
    const source = await client.getSource(queueId, reviewId, sourceIndex);
    preview.textContent = source.truncated ? `${source.content}\n[truncated]` : source.content;
  } catch (error) {
    preview.textContent = error.message;
  }
}

function renderFindings(packet) {
  const section = document.createElement("section");
  section.className = "findings-section";
  section.innerHTML = "<h3>Findings</h3>";
  for (const finding of packet.findings) {
    const card = els.findingTemplate.content.firstElementChild.cloneNode(true);
    card.dataset.findingId = finding.id;
    card.querySelector(".finding-title").textContent = `${finding.id} · ${finding.title}`;
    card.querySelector(".finding-meta").textContent = `${finding.category} · ${finding.location}`;
    card.querySelector(".finding-severity").textContent = finding.severity;
    card.querySelector(".finding-current").textContent = finding.current_value || "(empty)";
    card.querySelector(".finding-proposed").textContent = finding.proposed_value || "(empty)";
    card.querySelector(".finding-rationale").textContent = finding.rationale;
    card.querySelector(".finding-evidence").textContent = `Evidence: ${finding.evidence_refs.join(", ")}`;
    prepareDecisionControls(card, finding);
    section.append(card);
  }
  els.detail.append(section);
}

function prepareDecisionControls(card, finding) {
  const radios = [...card.querySelectorAll("input[type='radio']")];
  for (const radio of radios) {
    radio.name = `decision-${finding.id}`;
    radio.addEventListener("change", () => updateDecision(card, finding));
  }
  for (const field of card.querySelectorAll("textarea, select, input[type='text']")) {
    field.addEventListener("input", () => updateDecision(card, finding));
  }
  if (finding.auto_approved) {
    card.classList.add("auto-approved");
    card.querySelector(".decision-fieldset").disabled = true;
    card.querySelector(".decision-error").textContent = "Auto-approved by packet; no human action required.";
  }
}

function updateDecision(card, finding) {
  const selected = card.querySelector("input[type='radio']:checked")?.value;
  const conditional = card.querySelector(".conditional-fields");
  const modified = card.querySelector(".modified-field");
  const rejected = card.querySelector(".rejected-fields");
  conditional.hidden = selected !== "modified" && selected !== "rejected";
  modified.hidden = selected !== "modified";
  rejected.hidden = selected !== "rejected";
  if (!selected) {
    state.decisions.delete(finding.id);
    renderSubmitState();
    return;
  }
  const decision = { finding_id: finding.id, decision: selected };
  for (const field of card.querySelectorAll("[data-field]")) {
    if (!field.closest("[hidden]") && field.value) {
      decision[field.dataset.field] = field.value;
    }
  }
  state.decisions.set(finding.id, decision);
  renderSubmitState();
}

function renderSubmitPanel(detail) {
  const packet = detail.packet;
  const locked = detail.status !== "pending";
  const section = document.createElement("section");
  section.className = "submit-panel";
  section.innerHTML = `
    <h3>Submit decision</h3>
    <p id="submit-status">${locked ? formatStatus(detail.status) : "Complete every actionable finding before submitting."}</p>
    <label>Reviewer <input id="reviewer-input" type="text" ${locked ? "disabled" : ""} /></label>
    <label id="role-label" hidden>Reviewer role <select id="role-input" ${locked ? "disabled" : ""}></select></label>
    <label>General notes <textarea id="notes-input" rows="3" maxlength="1000" ${locked ? "disabled" : ""}></textarea></label>
    <div class="submit-actions">
      <button id="approve-all-button" class="button secondary" type="button" ${locked ? "disabled" : ""}>✓ Approve all</button>
      <button id="submit-button" class="button primary" type="button" disabled>Submit all</button>
    </div>
  `;
  els.detail.append(section);
  const roles = packet.required_reviewers || [];
  if (roles.length > 0) {
    const roleLabel = section.querySelector("#role-label");
    const roleInput = section.querySelector("#role-input");
    roleLabel.hidden = false;
    roleInput.append(new Option("Select role", ""));
    for (const role of roles) {
      roleInput.append(new Option(role.role, role.role));
    }
  }
  section.querySelector("#approve-all-button").addEventListener("click", approveAll);
  section.querySelector("#submit-button").addEventListener("click", submitAll);
  for (const input of section.querySelectorAll("input, textarea, select")) {
    input.addEventListener("input", renderSubmitState);
  }
  renderSubmitState();
}

function approveAll() {
  const actionable = state.detail.packet.findings.filter((finding) => !finding.auto_approved);
  if (!confirm(`Approve ${actionable.length} unresolved finding(s)?`)) {
    return;
  }
  for (const finding of actionable) {
    const card = document.querySelector(`[data-finding-id="${finding.id}"]`);
    const radio = card.querySelector("input[value='approved']");
    radio.checked = true;
    updateDecision(card, finding);
  }
}

function renderSubmitState() {
  const detail = state.detail;
  if (!detail) return;
  const packet = detail.packet;
  const actionableIds = packet.findings.filter((finding) => !finding.auto_approved).map((finding) => finding.id);
  const reviewer = document.querySelector("#reviewer-input");
  const role = document.querySelector("#role-input");
  const submit = document.querySelector("#submit-button");
  const status = document.querySelector("#submit-status");
  if (!submit || !status) return;
  const hasAllDecisions = actionableIds.every((id) => state.decisions.has(id));
  const hasReviewer = reviewer?.value.trim().length >= 2;
  const hasRole = !role || role.value;
  const locked = detail.status !== "pending";
  submit.disabled = locked || !hasAllDecisions || !hasReviewer || !hasRole;
  status.textContent = locked
    ? formatStatus(detail.status)
    : `${state.decisions.size}/${actionableIds.length} actionable findings decided.`;
}

async function submitAll() {
  const packet = state.detail.packet;
  const role = document.querySelector("#role-input");
  const payload = {
    review_id: packet.review_id,
    packet_sha256: state.detail.packet_sha256,
    reviewer: document.querySelector("#reviewer-input").value.trim(),
    reviewer_role: role?.value || undefined,
    general_notes: document.querySelector("#notes-input").value,
    decisions: [...state.decisions.values()],
  };
  const summary = payload.decisions.reduce((counts, item) => {
    counts[item.decision] = (counts[item.decision] || 0) + 1;
    return counts;
  }, {});
  if (!confirm(`Submit decisions? approved=${summary.approved || 0}, modified=${summary.modified || 0}, rejected=${summary.rejected || 0}`)) {
    return;
  }
  try {
    const result = await client.submitDecision(state.selected.queueId, state.selected.reviewId, payload);
    renderAlert(`DecisionReceipt written: ${result.receipt_file}`, "success");
    await selectReview(state.selected.queueId, state.selected.reviewId, { pushUrl: false });
  } catch (error) {
    renderAlert(error.message, "error");
  }
}

function renderAlerts(list) {
  els.globalAlerts.replaceChildren();
  if (!list.partial) {
    renderAlert("All trusted queues loaded.", "success");
    return;
  }
  for (const error of list.errors) {
    renderAlert(`${error.queue_id || "registry"}: ${error.message}`, "warning", false);
  }
}

function renderAlert(message, tone, replace = true) {
  if (replace) {
    els.globalAlerts.replaceChildren();
  }
  const item = document.createElement("p");
  item.className = `alert ${tone}`;
  item.textContent = message;
  els.globalAlerts.append(item);
}

function renderEmpty(title, message) {
  els.detail.hidden = true;
  els.detailEmpty.hidden = false;
  els.detailEmpty.innerHTML = `<h2>${escapeHtml(title)}</h2><p>${escapeHtml(message)}</p>`;
}

function setBusy(value) {
  els.shell.setAttribute("aria-busy", String(value));
}

function isSelected(queueId, reviewId) {
  return state.selected?.queueId === queueId && state.selected?.reviewId === reviewId;
}

function formatStatus(status) {
  const labels = {
    pending: "Pending human decision",
    decided_waiting_confirmation: "Decision submitted; waiting for Runtime confirmation",
    confirmed: "Runtime confirmation present",
    partial: "Partial data; review with caution",
    invalid: "Invalid review packet",
  };
  return labels[status] || status;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}
